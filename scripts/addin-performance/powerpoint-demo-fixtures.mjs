export function buildPowerPointDemoFixtures() {
  const short = coreMinutes.join('\n\n');
  const medium = [...coreMinutes, ...mediumDetails].join('\n\n');
  const long = [...coreMinutes, ...mediumDetails, ...longDetails].join('\n\n');
  return { short, medium, long };
}

export async function writePowerPointDemoFixtures(outputDir) {
  await fs.mkdir(outputDir, { recursive: true });
  const fixtures = buildPowerPointDemoFixtures();
  await Promise.all([
    ...Object.entries(fixtures).map(([name, prose]) =>
      fs.writeFile(path.join(outputDir, `${name}.txt`), prose, 'utf8'),
    ),
    fs.writeFile(
      path.join(outputDir, 'prompt.txt'),
      POWERPOINT_TEMPLATE_REPORT_PROMPT,
      'utf8',
    ),
  ]);
  return fixtures;
}

